/** Spaces in place of `text`. */
function blank(text: string): string {
  return " ".repeat(text.length);
}

// JavaScript white space and line terminators end a name.
const separators: ReadonlyArray<readonly [string, string]> = [
  ["U+00A0", "\u00a0"],
  ["U+FEFF", "\ufeff"],
  ["U+3000", "\u3000"],
  ["U+2028", "\u2028"],
];

describe("talk build lexer", () => {
  it.each([
    ["string literals", `a("x'y", 'p"q', "e\\"s")`, `a("   ", '   ', "    ")`],
    ["a line comment", 'a // b("x")\nc', `a ${blank('// b("x")')}\nc`],
    ["a block comment", "a/* import(n) */b", `a${blank("/* import(n) */")}b`],
    [
      "a comment between a word and a regular expression",
      "return /*c*/ /'/",
      `return ${blank("/*c*/")} / /`,
    ],
    ["template text", "`t}{x`", "`    `"],
    ["nested templates", '`t${`u${v}w`}x` + "r"', '` ${` ${v} `} ` + " "'],
    ["braces in a template expression", "`a${ {b:1}.b }c`", "` ${ {b:1}.b } `"],
    ["a division", 'a / b / "q"', 'a / b / " "'],
    [
      "a regular expression at the start",
      String.raw`/"[/]import(n)\//g, "q"`,
      `/${blank(String.raw`"[/]import(n)\/`)}/g, " "`,
    ],
    [
      "a regular expression after a word such as return",
      "return /'/.test(s)",
      "return / /.test(s)",
    ],
    ["a regular expression after the ) of if", "if (s) /'/.test(s)", "if (s) / /.test(s)"],
    ["a regular expression after }", "{}/'/.test(s)", "{}/ /.test(s)"],
    ["a division after the ) of a call", 'f(s) / 2 / "q"', 'f(s) / 2 / " "'],
    ["a division after ]", 'a[0] / 2 / "q"', 'a[0] / 2 / " "'],
    ["a division after ++", 'a++ / 2 / "q"', 'a++ / 2 / " "'],
    ["a division after a property named return", 'obj.return / b / "q"', 'obj.return / b / " "'],
    ["a division after a property named typeof", 'x?.typeof / b / "q"', 'x?.typeof / b / " "'],
    ["a division after the ) of a property named if", 'x.if(a) / b / "q"', 'x.if(a) / b / " "'],
    ["a regular expression after a spread of a keyword", "[...typeof /'/]", "[...typeof / /]"],
    [
      "a division after a private member named #return",
      'this.#return / b / "q"',
      'this.#return / b / " "',
    ],
  ])("blanks the text of %s", (_label, code, expected) => {
    expect(lexCode(code).text).toBe(expected);
  });

  it("keeps the close of each ( after an import word, nested or not closed", () => {
    expect([...lexCode("import(import(n))").importCalls]).toEqual([
      [0, 16],
      [7, 15],
    ]);
    expect([...lexCode("import(a").importCalls]).toEqual([[0, -1]]);
  });

  it("keeps no ( after a member, private, longer, or escaped name", () => {
    const code = String.raw`f(x.import(a), this.#import(b), αimport(c), \u{3b1}import(c), (e), import /* c */ (d))`;
    expect([...lexCode(code).importCalls]).toEqual([
      [code.indexOf("import /*"), code.indexOf("(d)") + 2],
    ]);
  });

  it.each(separators)("ends a name at %s", (_label, separator) => {
    expect([...lexCode(`import${separator}(name)`).importCalls]).toEqual([[0, 12]]);
  });

  it("finds require, __require, and import.meta.require calls but no other calls", () => {
    const code =
      'require("a");__require("b");import.meta.require("c");' +
      'x.require("d");x?.require("e");this.#require("f");#require(g){}' +
      'require.resolve("h");import.meta.resolve("i");require;("j")';
    const at = (text: string): number => code.indexOf(text);
    expect([...lexCode(code).requireCalls]).toEqual([
      [0, 7],
      [at("__require"), at('("b")')],
      [at("import.meta"), at('("c")')],
    ]);
  });
});

