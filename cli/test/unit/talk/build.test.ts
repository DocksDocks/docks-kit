const tempDirs: Array<string> = [];

function tempDir(label: string): string {
  const dir = mkdtempSync(join(tmpdir(), `talk-build-${label}-`));
  tempDirs.push(dir);
  return dir;
}

function runBuild(args: ReadonlyArray<string>): SpawnSyncReturns<string> {
  return spawnSync(BUN_RUNTIME, [BUILD_SCRIPT, ...args], { cwd: REPO_DIR, encoding: "utf8" });
}

/** A temporary project: one entry file and packages under its node_modules. A
 * package key is its folder under node_modules, such as `outer/node_modules/inner`. */
function tempProject(
  label: string,
  entry: string,
  packages: Readonly<Record<string, { readonly code: string; readonly license?: string }>>,
): string {
  const dir = tempDir(label);
  for (const [folder, { code, license }] of Object.entries(packages)) {
    const packageDir = join(dir, "node_modules", folder);
    const name = folder.split("/node_modules/").at(-1);
    mkdirSync(packageDir, { recursive: true });
    writeFileSync(
      join(packageDir, "package.json"),
      JSON.stringify({ name, version: "1.0.0", type: "module", main: "index.js" }),
    );
    writeFileSync(join(packageDir, "index.js"), code);
    if (license !== undefined) writeFileSync(join(packageDir, "LICENSE"), license);
  }
  writeFileSync(join(dir, "entry.js"), entry);
  return join(dir, "entry.js");
}

afterAll(() => {
  for (const dir of tempDirs) rmSync(dir, { recursive: true, force: true });
});

describe("talk build of cli/talk/index.ts", () => {
  let outDir = "";
  let result: SpawnSyncReturns<string>;
  let bundle = "";

  beforeAll(() => {
    outDir = tempDir("entry");
    result = runBuild(["--out", outDir]);
    const outFile = join(outDir, "talk.js");
    if (existsSync(outFile)) bundle = readFileSync(outFile, "utf8");
  });

  it("exits 0 and prints the output path and its size", () => {
    expect(result.stderr).toBe("");
    expect(result.status).toBe(0);
    const outFile = join(outDir, "talk.js");
    expect(result.stdout).toContain(outFile);
    expect(result.stdout).toContain(`${Buffer.byteLength(bundle)} bytes`);
  });

  it("starts with the generated-file header", () => {
    expect(GENERATED_HEADER).toMatch(/generated by cli\/scripts\/build-talk\.ts/i);
    expect(GENERATED_HEADER).not.toContain("\n");
    expect(bundle.startsWith(`${GENERATED_HEADER}\n`)).toBe(true);
  });

  it("holds the complete pi-intercom license, then the complete Effect license", () => {
    const piIntercomAt = bundle.indexOf(PI_INTERCOM_LICENSE);
    const effectAt = bundle.indexOf(EFFECT_LICENSE);
    expect(piIntercomAt).toBeGreaterThan(GENERATED_HEADER.length);
    expect(effectAt).toBeGreaterThan(piIntercomAt + PI_INTERCOM_LICENSE.length - 1);
  });

  it("leaves no import of effect in the code", () => {
    expect(bundle).not.toMatch(/from\s*["']effect/);
  });
});

