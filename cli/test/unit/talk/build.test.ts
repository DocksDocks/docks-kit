import { spawnSync, type SpawnSyncReturns } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { GENERATED_HEADER } from "../../../scripts/build-talk";
import { BUN_RUNTIME } from "../../lib/cliEntry";
import { REPO_DIR } from "../../lib/goldenResources";

const BUILD_SCRIPT = join(REPO_DIR, "cli", "scripts", "build-talk.ts");
const FIXTURE_ENTRY = join(REPO_DIR, "cli", "test", "fixtures", "talk", "host-import.fixture.js");
const PI_INTERCOM_LICENSE = readFileSync(
  join(REPO_DIR, "cli", "talk", "licenses", "pi-intercom.txt"),
  "utf8",
);
const EFFECT_LICENSE = readFileSync(join(REPO_DIR, "node_modules", "effect", "LICENSE"), "utf8");
const HOST_LITERAL = 'import("@oh-my-pi/pi-tui/text/width")';

const tempDirs: Array<string> = [];

function tempDir(label: string): string {
  const dir = mkdtempSync(join(tmpdir(), `talk-build-${label}-`));
  tempDirs.push(dir);
  return dir;
}

function runBuild(args: ReadonlyArray<string>): SpawnSyncReturns<string> {
  return spawnSync(BUN_RUNTIME, [BUILD_SCRIPT, ...args], { cwd: REPO_DIR, encoding: "utf8" });
}

/** A temporary project: one entry file and packages under its node_modules. */
function tempProject(
  label: string,
  entry: string,
  packages: Readonly<Record<string, { readonly code: string; readonly license?: string }>>,
): string {
  const dir = tempDir(label);
  for (const [name, { code, license }] of Object.entries(packages)) {
    const packageDir = join(dir, "node_modules", name);
    mkdirSync(packageDir, { recursive: true });
    writeFileSync(
      join(packageDir, "package.json"),
      JSON.stringify({ name, version: "1.0.0", type: "module", main: "index.js" }),
    );
    writeFileSync(join(packageDir, "index.js"), code);
    if (license !== undefined) writeFileSync(join(packageDir, "LICENSE"), license);
  }
  writeFileSync(join(dir, "entry.js"), entry);
  return join(dir, "entry.js");
}

afterAll(() => {
  for (const dir of tempDirs) rmSync(dir, { recursive: true, force: true });
});

describe("talk build of cli/talk/index.ts", () => {
  let outDir = "";
  let result: SpawnSyncReturns<string>;
  let bundle = "";

  beforeAll(() => {
    outDir = tempDir("entry");
    result = runBuild(["--out", outDir]);
    const outFile = join(outDir, "talk.js");
    if (existsSync(outFile)) bundle = readFileSync(outFile, "utf8");
  });

  it("exits 0 and prints the output path and its size", () => {
    expect(result.stderr).toBe("");
    expect(result.status).toBe(0);
    const outFile = join(outDir, "talk.js");
    expect(result.stdout).toContain(outFile);
    expect(result.stdout).toContain(`${Buffer.byteLength(bundle)} bytes`);
  });

  it("starts with the generated-file header", () => {
    expect(GENERATED_HEADER).toMatch(/generated by cli\/scripts\/build-talk\.ts/i);
    expect(GENERATED_HEADER).not.toContain("\n");
    expect(bundle.startsWith(`${GENERATED_HEADER}\n`)).toBe(true);
  });

  it("holds the complete pi-intercom license, then the complete Effect license", () => {
    const piIntercomAt = bundle.indexOf(PI_INTERCOM_LICENSE);
    const effectAt = bundle.indexOf(EFFECT_LICENSE);
    expect(piIntercomAt).toBeGreaterThan(GENERATED_HEADER.length);
    expect(effectAt).toBeGreaterThan(piIntercomAt + PI_INTERCOM_LICENSE.length - 1);
  });

  it("leaves no import of effect in the code", () => {
    expect(bundle).not.toMatch(/from\s*["']effect/);
  });
});

describe("talk build license banner", () => {
  it("puts pi-intercom first, then Effect, then the other packages sorted by name", () => {
    const zetaLicense = "Zeta license text.\nCopyright zeta.\n";
    const alphaLicense = "Alpha license text.\nCopyright alpha.\n";
    const entry = tempProject(
      "order",
      [
        'import { zeta } from "zeta-pkg";',
        'import { alpha } from "alpha-pkg";',
        'import { Effect } from "effect";',
        "export const all = Effect.succeed([zeta(), alpha()]);",
        "",
      ].join("\n"),
      {
        "zeta-pkg": {
          code: 'export const zeta = () => "zeta-" + Math.random();\n',
          license: zetaLicense,
        },
        "alpha-pkg": {
          code: 'export const alpha = () => "alpha-" + Math.random();\n',
          license: alphaLicense,
        },
      },
    );
    symlinkSync(
      join(REPO_DIR, "node_modules", "effect"),
      join(entry, "..", "node_modules", "effect"),
    );
    const outDir = tempDir("order-out");
    const result = runBuild(["--entry", entry, "--out", outDir]);
    expect(result.stderr).toBe("");
    expect(result.status).toBe(0);
    const bundle = readFileSync(join(outDir, "talk.js"), "utf8");
    const order = [PI_INTERCOM_LICENSE, EFFECT_LICENSE, alphaLicense, zetaLicense].map((text) =>
      bundle.indexOf(text),
    );
    expect(order.every((at) => at > 0)).toBe(true);
    expect([...order].sort((a, b) => a - b)).toEqual(order);
  });

  it("fails and names a contributing package without a license file", () => {
    const entry = tempProject(
      "nolicense",
      'import { value } from "no-license-pkg";\nexport const out = value();\n',
      { "no-license-pkg": { code: 'export const value = () => "x-" + Math.random();\n' } },
    );
    const outDir = tempDir("nolicense-out");
    const result = runBuild(["--entry", entry, "--out", outDir]);
    expect(result.status).not.toBe(0);
    expect(result.stderr).toContain("MissingLicenseError");
    expect(result.stderr).toContain("no-license-pkg");
    expect(existsSync(join(outDir, "talk.js"))).toBe(false);
  });
});

describe("talk build host imports", () => {
  it("keeps a literal dynamic host import external and literal", () => {
    const outDir = tempDir("fixture-out");
    const result = runBuild(["--entry", FIXTURE_ENTRY, "--out", outDir]);
    expect(result.stderr).toBe("");
    expect(result.status).toBe(0);
    expect(readFileSync(join(outDir, "talk.js"), "utf8")).toContain(HOST_LITERAL);
  });

  const rejected: ReadonlyArray<readonly [string, string]> = [
    ["a static import", 'import * as tui from "@oh-my-pi/pi-tui";\nexport const t = tui;\n'],
    ["an export from", 'export { width } from "@oh-my-pi/pi-tui/text/width";\n'],
    ["a require call", 'export const load = () => require("@oh-my-pi/pi-tui");\n'],
    ["a dynamic import of a variable", "export const load = (name) => import(name);\n"],
  ];

  it.each(rejected)("fails on %s with HostImportError", (label, source) => {
    const entry = tempProject(label.replaceAll(" ", "-"), source, {});
    const outDir = tempDir("rejected-out");
    const result = runBuild(["--entry", entry, "--out", outDir]);
    expect(result.status).not.toBe(0);
    expect(result.stderr).toContain("HostImportError");
    expect(existsSync(join(outDir, "talk.js"))).toBe(false);
  });
});

describe("talk build command line", () => {
  it("fails with a clear message without --out", () => {
    const result = runBuild([]);
    expect(result.status).not.toBe(0);
    expect(result.stderr).toContain("--out");
  });
});
