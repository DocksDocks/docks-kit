/// <reference types="bun" />

// Builds the talk extension: one Bun bundle of cli/talk/index.ts in
// <out>/talk.js. omp loads that file, so the omp host modules (@oh-my-pi/*)
// stay external, and the code may load them only through a dynamic import of
// one string literal. The file starts with a generated-file header and a
// banner with the complete license text of each source that it holds code of.

import { randomUUID } from "node:crypto";
import {
  closeSync,
  mkdirSync,
  openSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { parseArgs } from "node:util";

const REPO_DIR = resolve(import.meta.dirname, "..", "..");

/** The bundle entry. */
export const TALK_ENTRY = join(REPO_DIR, "cli", "talk", "index.ts");

/** The bundle file name in the output folder. */
export const TALK_FILE = "talk.js";

/** The first line of the bundle. */
export const GENERATED_HEADER =
  "// Generated by cli/scripts/build-talk.ts. Do not edit; rebuild with: bun cli/scripts/build-talk.ts --out <dir>";

/** License texts of ported source, one `<name>.txt` per origin. They come first in the banner. */
const PORTED_LICENSES_DIR = join(REPO_DIR, "cli", "talk", "licenses");
const PORTED_LICENSE_SUFFIX = ".txt";

/** The package whose license comes right after the ported licenses. */
const FIRST_PACKAGE = "effect";

/** The license file names of a package, in lookup order. */
const LICENSE_FILES: ReadonlyArray<string> = ["LICENSE", "LICENSE.md", "LICENSE.txt"];

/** The path component that holds packages. */
const NODE_MODULES = "node_modules";
const SCOPE_PREFIX = "@";

const COMMENT_END = "*/";

// The host-import rules check the emitted code, so they also see an import
// that a dependency adds. Bun reports the static forms. lexCode() finds the
// loader calls by whole tokens, so text in a string, a comment, or a regular
// expression, and a longer or member name, does not match them.
const HOST_PREFIX = "@oh-my-pi/";
const DYNAMIC_IMPORT_KIND = "dynamic-import";
// In lexCode() text, a string literal is two quotes with only spaces between them.
const LITERAL_IMPORT = /import\s*\(\s*(?:" *"|' *')\s*\)/y;
// After the ")" of `import(...)`, a "{" starts the body of a method definition.
const METHOD_BODY = /\s*\{/y;
// The spaces before the quote that starts a call argument.
const QUOTED_ARGUMENT = /\s*(?=["'`])/y;
const SNIPPET_LENGTH = 60;

/** A package that adds code to the bundle has no license file. */
export class MissingLicenseError extends Error {
  override readonly name = "MissingLicenseError";
  constructor(
    readonly packageName: string,
    readonly packageDir: string,
  ) {
    super(
      `package ${packageName} adds code to ${TALK_FILE} but has none of ${LICENSE_FILES.join(", ")} in ${packageDir}`,
    );
  }
}

/** The emitted code loads a host module in a form other than a literal dynamic import. */
export class HostImportError extends Error {
  override readonly name = "HostImportError";
  constructor(readonly problems: ReadonlyArray<string>) {
    super(
      `${TALK_FILE} may load @oh-my-pi/ modules only with import("<literal>"), and every dynamic import ` +
        `needs one string literal: ${problems.join("; ")}`,
    );
  }
}

/** A license text would end the banner comment early. */
export class LicenseTextError extends Error {
  override readonly name = "LicenseTextError";
  constructor(readonly source: string) {
    super(
      `the license text of ${source} holds "${COMMENT_END}", so the banner comment cannot hold it`,
    );
  }
}

/** Bun could not bundle the entry. */
export class BundleError extends Error {
  override readonly name = "BundleError";
}

/** One banner section: whose license, and its complete text. */
export interface LicenseSection {
  readonly source: string;
  readonly text: string;
}

/** A package that adds code to the bundle. */
export interface ContributingPackage {
  readonly name: string;
  readonly dir: string;
}

function snippet(code: string, at: number): string {
  return JSON.stringify(code.slice(at, at + SNIPPET_LENGTH));
}

/** The ways the emitted code breaks the host-import rules; empty when it holds.
 *
 * Limits: the rules use a lexer, not a parser. A "/" after the ")" of a call
 * counts as a division and a "/" after "}" as a regular expression. A call
 * `import(x)` followed by a new line and a block counts as a method definition.
 * A loader that the code reaches through another name, such as
 * `const load = require` or `import.meta["require"]`, is not seen, and an
 * escape in a loader name, such as `requ\u0069re`, is not decoded. */
export function hostImportProblems(code: string): ReadonlyArray<string> {
  const problems: Array<string> = [];
  for (const { kind, path } of new Bun.Transpiler({ loader: "js" }).scanImports(code)) {
    if (path.startsWith(HOST_PREFIX) && kind !== DYNAMIC_IMPORT_KIND) {
      problems.push(`${kind} of ${JSON.stringify(path)}`);
    }
  }
  return [...problems, ...loaderCallProblems(code)];
}

/** The `require` calls of host modules and the dynamic imports without one
 * string literal in `code`. Unlike hostImportProblems(), it does not need Bun. */
export function loaderCallProblems(code: string): ReadonlyArray<string> {
  const problems: Array<string> = [];
  const { text, importCalls, requireCalls } = lexCode(code);
  for (const [start, open] of requireCalls) {
    QUOTED_ARGUMENT.lastIndex = open + 1;
    if (QUOTED_ARGUMENT.test(text) && code.startsWith(HOST_PREFIX, QUOTED_ARGUMENT.lastIndex + 1)) {
      problems.push(`require at offset ${start}: ${snippet(code, start)}`);
    }
  }
  for (const [start, close] of importCalls) {
    LITERAL_IMPORT.lastIndex = start;
    if (LITERAL_IMPORT.test(text)) continue;
    // A method named `import`, such as `import(name) { ... }`, is not an import.
    METHOD_BODY.lastIndex = close + 1;
    if (close !== -1 && METHOD_BODY.test(text)) continue;
    problems.push(
      `dynamic import without one string literal at offset ${start}: ${snippet(code, start)}`,
    );
  }
  return problems;
}

const SPACE_CHAR = /\s/;
const WORD_CHAR = /[\w$\u0080-\uffff]/;
// Bun writes a non-ASCII identifier character as an escape such as `\u{3b1}`.
const UNICODE_ESCAPE = /\\u(?:\{[0-9a-fA-F]+\}|[0-9a-fA-F]{4})/y;

/** The length of the identifier part at `at`: one character, a `\uXXXX` or
 * `\u{...}` escape, or 0 when no identifier part starts there. */
function identifierPartLength(code: string, at: number): number {
  if (WORD_CHAR.test(code[at] ?? "")) return 1;
  UNICODE_ESCAPE.lastIndex = at;
  return UNICODE_ESCAPE.test(code) ? UNICODE_ESCAPE.lastIndex - at : 0;
}

/** After one of these words, a "/" starts a regular expression. */
const WORDS_BEFORE_EXPRESSION: Readonly<Record<string, true>> = {
  await: true,
  case: true,
  delete: true,
  do: true,
  else: true,
  in: true,
  instanceof: true,
  new: true,
  of: true,
  return: true,
  throw: true,
  typeof: true,
  void: true,
  yield: true,
};
/** After the "(...)" of one of these words, a "/" starts a regular expression. */
const CONTROL_WORDS: Readonly<Record<string, true>> = {
  for: true,
  if: true,
  while: true,
  with: true,
};

/** The result of lexCode(). */
export interface LexedCode {
  /** The code with the text of each string literal, template literal, comment,
   * and regular expression literal replaced by spaces. */
  readonly text: string;
  /** For each `import` word followed by "(": the offset of the ")" that closes
   * that "(", or -1 when none does, by the offset of the word. */
  readonly importCalls: ReadonlyMap<number, number>;
  /** For each call of `require`, of another name that ends in `require` such as
   * `__require`, or of `import.meta.require`: the offset of its "(", by the
   * offset of the name. A member call such as `x.require(` is not one. */
  readonly requireCalls: ReadonlyMap<number, number>;
}

/** What the tokens before a "(" call: nothing that matters, the `import` word,
 * `import.meta`, or a `require` loader. */
type Callee = "none" | "import" | "import.meta" | "require";

// The stack entry of a "(" that does not follow `import`; an `import(` entry is
// the offset of its word.
const PLAIN_PAREN = -1;
const CONTROL_PAREN = -2;

/** Lex `code` in one pass. In the returned text, quotes, backticks, the `${`
 * and `}` of a template, and the slashes and flags of a regular expression
 * stay, and each offset stays the same. A "/" starts a regular expression at
 * the start, after an operator, an opening bracket, `}`, a word such as
 * `return`, or the `)` of `if (...)`, `for (...)`, `while (...)`, or
 * `with (...)`; otherwise it is a division. A word after "." or "?." and a
 * private name such as `#return` are member names, not keywords. A name with
 * escapes, such as `\u{3b1}import`, is one word. */
export function lexCode(code: string): LexedCode {
  const parts: Array<string> = [];
  let copied = 0;
  const blank = (from: number, to: number): void => {
    const end = Math.min(to, code.length);
    if (end <= from) return;
    parts.push(code.slice(copied, from), " ".repeat(end - from));
    copied = end;
  };
  const importCalls = new Map<number, number>();
  const requireCalls = new Map<number, number>();
  // The brace depth at each open template `${`, innermost last.
  const templateBraces: Array<number> = [];
  // Each open "(": the offset of its `import` word, PLAIN_PAREN, or CONTROL_PAREN.
  const openParens: Array<number> = [];
  let braces = 0;
  let regexNext = true;
  let word = "";
  // Whether the token before is the "." of a property access.
  let propertyNext = false;
  let callee: Callee = "none";
  let calleeStart = 0;
  let at = 0;

  // Skip template text from `at` to the closing backtick or the next `${`.
  const templateText = (): void => {
    const start = at;
    while (at < code.length && code[at] !== "`" && !(code[at] === "$" && code[at + 1] === "{")) {
      at += code[at] === "\\" ? 2 : 1;
    }
    blank(start, at);
    if (code[at] === "`") {
      at += 1;
      regexNext = false;
    } else if (at < code.length) {
      at += 2;
      templateBraces.push(braces);
      regexNext = true;
    }
  };

  while (at < code.length) {
    const char = code[at] ?? "";
    const next = code[at + 1];
    if (SPACE_CHAR.test(char)) {
      at += 1;
      continue;
    }
    // A private name `#name` is one member-name token, never a keyword or a loader.
    const privateName = char === "#" && identifierPartLength(code, at + 1) > 0;
    if (privateName || identifierPartLength(code, at) > 0) {
      const start = at;
      at += privateName ? 1 : 0;
      let part = identifierPartLength(code, at);
      while (part > 0) {
        at += part;
        part = identifierPartLength(code, at);
      }
      const name = code.slice(start, at);
      if (propertyNext || privateName) {
        // A member name continues `import.meta.require`; any other ends the callee.
        if (callee === "import" && name === "meta") callee = "import.meta";
        else if (callee === "import.meta" && name === "require") callee = "require";
        else callee = "none";
        word = "";
      } else {
        if (name === "import") callee = "import";
        else if (name.endsWith("require")) callee = "require";
        else callee = "none";
        calleeStart = start;
        word = name;
      }
      propertyNext = false;
      regexNext = WORDS_BEFORE_EXPRESSION[word] === true;
      continue;
    }
    // A comment keeps the word and the "/" rule of the token before it.
    if (char === "/" && next === "/") {
      const end = code.indexOf("\n", at);
      const stop = end === -1 ? code.length : end;
      blank(at, stop);
      at = stop;
      continue;
    }
    if (char === "/" && next === "*") {
      const end = code.indexOf("*/", at + 2);
      const stop = end === -1 ? code.length : end + 2;
      blank(at, stop);
      at = stop;
      continue;
    }
    const before = word;
    const called = callee;
    word = "";
    propertyNext = char === "." && next !== "." && code[at - 1] !== ".";
    // A property "." keeps the callee for the member name after it.
    if (!propertyNext) callee = "none";
    if (char === '"' || char === "'") {
      let end = at + 1;
      while (end < code.length && code[end] !== char) end += code[end] === "\\" ? 2 : 1;
      blank(at + 1, end);
      at = end + 1;
      regexNext = false;
      continue;
    }
    if (char === "`") {
      at += 1;
      templateText();
      continue;
    }
    if (char === "/" && regexNext) {
      let end = at + 1;
      let inClass = false;
      while (end < code.length && code[end] !== "\n") {
        const bodyChar = code[end];
        if (bodyChar === "\\") {
          end += 2;
          continue;
        }
        if (bodyChar === "/" && !inClass) break;
        if (bodyChar === "[") inClass = true;
        else if (bodyChar === "]") inClass = false;
        end += 1;
      }
      blank(at + 1, end);
      at = end + 1;
      while (at < code.length && WORD_CHAR.test(code[at] ?? "")) at += 1;
      regexNext = false;
      continue;
    }
    if (char === "}" && templateBraces.at(-1) === braces) {
      templateBraces.pop();
      at += 1;
      templateText();
      continue;
    }
    // A regular expression cannot follow `++` or `--`, so a "/" there is a division.
    if ((char === "+" || char === "-") && next === char) {
      at += 2;
      regexNext = false;
      continue;
    }
    if (char === "(") {
      if (called === "import") {
        importCalls.set(calleeStart, -1);
        openParens.push(calleeStart);
      } else {
        if (called === "require") requireCalls.set(calleeStart, at);
        openParens.push(CONTROL_WORDS[before] === true ? CONTROL_PAREN : PLAIN_PAREN);
      }
    }
    if (char === "{") braces += 1;
    if (char === "}") braces -= 1;
    if (char === ")") {
      const open = openParens.pop() ?? PLAIN_PAREN;
      if (open >= 0) importCalls.set(open, at);
      regexNext = open === CONTROL_PAREN;
    } else regexNext = char !== "]";
    at += 1;
  }
  parts.push(code.slice(copied));
  return { text: parts.join(""), importCalls, requireCalls };
}

/** The package that holds a metafile input path, or undefined for source outside node_modules.
 * It is the package after the last `node_modules` component that has a package root
 * (`<name>` or `@scope/<name>`) and a file path below that root. */
export function packageOfInput(input: string, cwd: string): ContributingPackage | undefined {
  const parts = input.replaceAll("\\", "/").split("/");
  for (let at = parts.length - 1; at >= 0; at -= 1) {
    if (parts[at] !== NODE_MODULES) continue;
    const first = parts[at + 1] ?? "";
    const rootEnd = at + (first.startsWith(SCOPE_PREFIX) ? 3 : 2);
    const nameParts = parts.slice(at + 1, rootEnd);
    // A package root needs its full name and a file below it.
    if (rootEnd >= parts.length || nameParts.some((part) => part.length === 0)) continue;
    return {
      name: nameParts.join("/"),
      dir: resolve(cwd, parts.slice(0, rootEnd).join("/")),
    };
  }
  return undefined;
}

/** The packages of the inputs that add bytes to the output: Effect first, then by name. */
export function contributingPackages(
  inputs: Readonly<Record<string, { readonly bytesInOutput: number }>>,
  cwd: string,
): ReadonlyArray<ContributingPackage> {
  const byDir = new Map<string, ContributingPackage>();
  for (const [input, { bytesInOutput }] of Object.entries(inputs)) {
    if (bytesInOutput <= 0) continue;
    const found = packageOfInput(input, cwd);
    if (found !== undefined && !byDir.has(found.dir)) byDir.set(found.dir, found);
  }
  const rank = (name: string): number => (name === FIRST_PACKAGE ? 0 : 1);
  return [...byDir.values()].sort(
    (a, b) =>
      rank(a.name) - rank(b.name) ||
      a.name.localeCompare(b.name, "en") ||
      a.dir.localeCompare(b.dir, "en"),
  );
}

function readPackageLicense({ name, dir }: ContributingPackage): string {
  for (const file of LICENSE_FILES) {
    try {
      return readFileSync(join(dir, file), "utf8");
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
  }
  throw new MissingLicenseError(name, dir);
}

function portedLicenses(): ReadonlyArray<LicenseSection> {
  return readdirSync(PORTED_LICENSES_DIR)
    .filter((file) => file.endsWith(PORTED_LICENSE_SUFFIX))
    .sort()
    .map((file) => ({
      source: `${basename(file, PORTED_LICENSE_SUFFIX)} (ported source)`,
      text: readFileSync(join(PORTED_LICENSES_DIR, file), "utf8"),
    }));
}

/** The banner comment: each section's complete text, in the given order. */
export function licenseBanner(sections: ReadonlyArray<LicenseSection>): string {
  const parts = ["/*", `Licenses of the code in ${TALK_FILE}:`, ""];
  for (const { source, text } of sections) {
    if (text.includes(COMMENT_END)) throw new LicenseTextError(source);
    parts.push(`== ${source} ==`, "", text.endsWith("\n") ? text.slice(0, -1) : text, "");
  }
  parts.push(COMMENT_END);
  return `${parts.join("\n")}\n`;
}

/** Bundle `entry` into `<outDir>/talk.js`; returns the file path and its size in bytes. */
export async function buildTalk({
  entry,
  outDir,
}: {
  readonly entry: string;
  readonly outDir: string;
}): Promise<{ readonly path: string; readonly bytes: number }> {
  const result = await Bun.build({
    entrypoints: [entry],
    target: "bun",
    external: ["@oh-my-pi/*"],
    minify: { whitespace: true, syntax: true },
    metafile: true,
    throw: false,
  });
  if (!result.success) {
    throw new BundleError(result.logs.map((log) => String(log)).join("\n"));
  }
  const [artifact] = result.outputs;
  const outputs = Object.values(result.metafile?.outputs ?? {});
  if (result.outputs.length !== 1 || artifact === undefined || outputs.length !== 1) {
    throw new BundleError(
      `expected one output and its metafile entry, got ${result.outputs.length}`,
    );
  }
  const code = await artifact.text();
  const problems = hostImportProblems(code);
  if (problems.length > 0) throw new HostImportError(problems);

  const packages = contributingPackages(outputs[0]?.inputs ?? {}, process.cwd());
  const banner = licenseBanner([
    ...portedLicenses(),
    ...packages.map((found) => ({ source: found.name, text: readPackageLicense(found) })),
  ]);
  const bundle = `${GENERATED_HEADER}\n${banner}${code}`;
  mkdirSync(outDir, { recursive: true });
  const path = join(outDir, TALK_FILE);
  writeReplacing(path, bundle);
  return { path, bytes: Buffer.byteLength(bundle) };
}

/** Write `content` to a new file in the folder of `path`, then rename it over
 * `path`. The rename replaces a link at `path` and does not follow it. */
function writeReplacing(path: string, content: string): void {
  const temporary = join(dirname(path), `.${basename(path)}.${randomUUID()}.tmp`);
  // "wx" fails when the name exists, so this run created the file that it removes.
  const fd = openSync(temporary, "wx");
  try {
    try {
      writeFileSync(fd, content);
    } finally {
      closeSync(fd);
    }
    renameSync(temporary, path);
  } catch (error) {
    rmSync(temporary, { force: true });
    throw error;
  }
}

const USAGE = "usage: bun cli/scripts/build-talk.ts --out <dir> [--entry <file>]";

async function main(): Promise<void> {
  try {
    const { values } = parseArgs({
      options: { out: { type: "string" }, entry: { type: "string" } },
      strict: true,
      allowPositionals: false,
    });
    if (values.out === undefined) throw new Error(`--out <dir> is required; ${USAGE}`);
    const { path, bytes } = await buildTalk({
      entry: resolve(values.entry ?? TALK_ENTRY),
      outDir: resolve(values.out),
    });
    console.log(`[build-talk] ${path}, ${bytes} bytes`);
  } catch (error) {
    console.error(
      `[build-talk] ${error instanceof Error ? `${error.name}: ${error.message}` : String(error)}`,
    );
    process.exit(1);
  }
}

if (import.meta.main) await main();
